export interface ElementData {
  number: number;
  symbol: string;
  name: string;
  period: number;
  group: number;
  category: 'nonmetal' | 'noble' | 'alkali' | 'alkaline' | 'metalloid' | 'halogen' | 'transition';
  categoryKo: string;
  english: string;
  weight: string;
  state: string; // 상온 상태 (기체, 고체, 액체)
  description: string; // 중3 과학 핵심 특징
}

export interface IonData {
  id: string;
  formula: string; // Plain text representation (e.g. "Na+", "SO4 2-")
  htmlFormula: string; // HTML formatted (e.g. "Na<sup>+</sup>", "SO<sub>4</sub><sup>2-</sup>")
  name: string;
  rootName: string; // Name without "이온" (e.g. "나트륨")
  aliases: string[]; // Allowed input answers for Stage 4
  type: 'cation' | 'anion';
  charge: number; // positive for cations, negative for anions
}

